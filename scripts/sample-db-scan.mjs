// Builds public/sample-db/manifest.json from the files you dropped in the folders.
// Files are matched by name: photos/m-pier.jpg -> memory "m-pier".
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { join, extname, basename } from "node:path";

const root = new URL("../public/sample-db/", import.meta.url).pathname.replace(
  /^\/([A-Za-z]:)/,
  "$1",
);
const kinds = {
  photos: { key: "image", exts: [".jpg", ".jpeg", ".png", ".webp"] },
  videos: { key: "video", exts: [".mp4", ".webm", ".mov"] },
  audio: { key: "audio", exts: [".mp3", ".m4a", ".wav", ".ogg"] },
};
const avatarExts = [".jpg", ".jpeg", ".png", ".webp"];

const memories = {};
const people = {};
const list = (dir) =>
  existsSync(join(root, dir)) ? readdirSync(join(root, dir)) : [];

for (const [dir, { key, exts }] of Object.entries(kinds)) {
  for (const file of list(dir)) {
    const ext = extname(file).toLowerCase();
    if (!exts.includes(ext)) continue;
    const id = basename(file, extname(file));
    memories[id] ??= {};
    memories[id][key] = `${dir}/${file}`;
  }
}
// A photo with the same id as a video becomes its cover image.
for (const entry of Object.values(memories)) {
  if (entry.video && entry.image) {
    entry.poster = entry.image;
    delete entry.image;
  }
}
for (const file of list("avatars")) {
  const ext = extname(file).toLowerCase();
  if (avatarExts.includes(ext)) people[basename(file, ext)] = `avatars/${file}`;
}

const manifest = {
  _note:
    "Generated by `npm run sample-db`. Drop files in the folders, run the command, refresh the page.",
  memories,
  people,
};
const found = Object.keys(memories).length + Object.keys(people).length;
if (process.argv.includes("--list")) {
  console.log(JSON.stringify(manifest, null, 2));
} else {
  writeFileSync(
    join(root, "manifest.json"),
    JSON.stringify(manifest, null, 2) + "\n",
  );
  console.log(
    `sample-db: ${Object.keys(memories).length} memories and ${Object.keys(people).length} people found. manifest.json updated.`,
  );
  if (!found) console.log("No files yet. See public/sample-db/README.md.");
}
