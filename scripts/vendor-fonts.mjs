// Vendors the pinned PDF renderer fonts (CH-10) from google/fonts at the
// commit in src/lib/render/fonts/fonts.json. Each TTF is checked against its
// pinned SHA-256 and written as a base64 module, so the renderer needs no
// fetch or file system in the browser or Node. Licenses are copied beside it.
//
//   node scripts/vendor-fonts.mjs          verify pins, rewrite data modules
//   node scripts/vendor-fonts.mjs --pin    record digests/versions of new entries
//   node scripts/vendor-fonts.mjs --from <dir>  read <dir>/<path> instead of downloading
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import fontkit from "@pdf-lib/fontkit";

const root = new URL("../src/lib/render/fonts/", import.meta.url);
const catalogUrl = new URL("fonts.json", root);
const catalog = JSON.parse(await readFile(catalogUrl, "utf8"));
const args = process.argv.slice(2);
const pin = args.includes("--pin");
const from = args.includes("--from") ? args[args.indexOf("--from") + 1] : null;

async function load(path) {
  if (from) return new Uint8Array(await readFile(join(from, path)));
  const url = `https://raw.githubusercontent.com/google/fonts/${catalog.commit}/${path}`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return new Uint8Array(await response.arrayBuffer());
}

const licenses = new Set();
for (const font of catalog.fonts) {
  const bytes = await load(font.path);
  const sha256 = createHash("sha256").update(bytes).digest("hex");
  if (font.sha256 && font.sha256 !== sha256)
    throw new Error(`${font.path}: SHA-256 ${sha256} != pinned ${font.sha256}`);
  if (!font.sha256 && !pin)
    throw new Error(`${font.path}: not pinned; rerun with --pin`);
  const parsed = fontkit.create(bytes);
  font.sha256 = sha256;
  font.size = bytes.length;
  const version = parsed.getName("version") ?? "";
  font.version = /^Version [0-9.]+/.exec(version)?.[0] ?? version;
  font.postscriptName = parsed.postscriptName;
  await writeFile(
    new URL(`data/${font.id}.ts`, root),
    `// Generated by scripts/vendor-fonts.mjs. Do not edit.\n` +
      `// ${font.family} ${font.style}, ${font.version}, SIL Open Font License 1.1.\n` +
      `// google/fonts@${catalog.commit} ${font.path}\n` +
      `// SHA-256 of the decoded bytes: ${sha256}\n` +
      `const base64 =\n  "${Buffer.from(bytes).toString("base64")}";\nexport default base64;\n`,
  );
  licenses.add(font.license);
}
for (const path of licenses) {
  const text = new TextDecoder().decode(await load(path));
  const name = path.split("/")[1];
  await writeFile(new URL(`licenses/${name}-OFL.txt`, root), text);
}
await writeFile(catalogUrl, `${JSON.stringify(catalog, null, 2)}\n`);
for (const font of catalog.fonts)
  console.log(
    `${font.id}\t${font.version}\t${font.size}\t${font.sha256}\t${font.postscriptName}`,
  );
